import { writeFileSync } from 'fs';

// CC64最小診断用: Ch1で 127(ON) → 0(OFF) の2イベントのみ
const midi = new Uint8Array([
  // Header
  0x4D,0x54,0x68,0x64,  0x00,0x00,0x00,0x06,  0x00,0x00, 0x00,0x01, 0x01,0xE0,
  // Track
  0x4D,0x54,0x72,0x6B,  0x00,0x00,0x00,0x12,
  // Tempo 120bpm
  0x00,0xFF,0x51,0x03,0x07,0xA1,0x20,
  // CC64 ON (Ch1)
  0x00,0xB1,0x40,0x7F,
  // wait 480
  0x81,0xE0,
  // CC64 OFF (Ch1)
  0xB1,0x40,0x00,
  // EOT
  0x00,0xFF,0x2F,0x00
]);

writeFileSync('data/export/cc64_min_ch1_on_off.mid', midi);
console.log('✅ 生成: data/export/cc64_min_ch1_on_off.mid');
